std::string pythonBuildName(int major, int minor, bool freeThreaded) {
	return std::to_string(major) + "." + std::to_string(minor) + (freeThreaded ? "t (free-threaded)" : " (with GIL)");
}

// Interpreter named by the algorithm's shebang line, or "" when there is none.
// "#!/usr/bin/env [options] name" is resolved through PATH; a relative path is
// taken relative to the algorithm file.
bool shebangInterpreter(const std::string& algorithmFile, std::string& interpreter, std::string& error) {
	interpreter.clear();
	FILE* file = fopen(algorithmFile.c_str(), "r");
	if (!file) { error = "cannot read " + algorithmFile; return false; }
	char line[4096] = { 0 };
	const bool read = fgets(line, sizeof(line), file) != nullptr;
	fclose(file);
	if (!read || line[0] != '#' || line[1] != '!') return true;
	std::vector<std::string> tokens;
	std::istringstream stream(std::string(line + 2));
	for (std::string token; stream >> token;) tokens.push_back(token);
	if (tokens.empty()) return true;
	std::string name = tokens[0];
	const bool viaEnv = name.size() >= 4 && name.compare(name.size() - 4, 4, "/env") == 0;
	if (viaEnv) {
		name.clear();
		for (size_t i = 1; i < tokens.size(); ++i) {
			if (tokens[i][0] == '-' || tokens[i].find('=') != std::string::npos) continue; // env options / assignments
			name = tokens[i];
			break;
		}
		if (name.empty()) { error = algorithmFile + ": shebang '" + tokens[0] + "' names no interpreter"; return false; }
		if (name.find('/') == std::string::npos) {
			const char* pathEnv = getenv("PATH");
			std::istringstream paths(pathEnv ? pathEnv : "");
			std::string found;
			for (std::string folder; std::getline(paths, folder, ':');) {
				const std::string candidate = (folder.empty() ? std::string(".") : folder) + "/" + name;
				if (access(candidate.c_str(), X_OK) == 0) { found = candidate; break; }
			}
			if (found.empty()) { error = algorithmFile + " asks for '" + name + "' (shebang), which is not on the server's PATH"; return false; }
			name = found;
		}
	}
	if (name[0] != '/') name = directoryOf(algorithmFile) + "/" + name;
	if (access(name.c_str(), X_OK) != 0) {
		error = algorithmFile + " asks for the Python environment " + name + " (shebang), which does not exist anymore";
		return false;
	}
	interpreter = name;
	return true;
}

// Runs `interpreter -I -c code` (before the embedded interpreter starts, no
// threads yet) and returns its standard output.
bool queryInterpreter(const std::string& interpreter, const char* code, std::string& output) {
	int pipeFds[2];
	if (pipe(pipeFds) != 0) return false;
	const pid_t pid = fork();
	if (pid < 0) { close(pipeFds[0]); close(pipeFds[1]); return false; }
	if (pid == 0) {
		dup2(pipeFds[1], STDOUT_FILENO);
		const int devNull = open("/dev/null", O_WRONLY);
		if (devNull >= 0) dup2(devNull, STDERR_FILENO);
		close(pipeFds[0]);
		close(pipeFds[1]);
		execl(interpreter.c_str(), interpreter.c_str(), "-I", "-c", code, static_cast<char*>(nullptr));
		_exit(127);
	}
	close(pipeFds[1]);
	output.clear();
	char buffer[512];
	ssize_t count;
	while ((count = read(pipeFds[0], buffer, sizeof(buffer))) > 0) output.append(buffer, size_t(count));
	close(pipeFds[0]);
	int status = 0;
	waitpid(pid, &status, 0);
	return WIFEXITED(status) && WEXITSTATUS(status) == 0;
}

// The environment must come from the same Python (version and GIL build) as
// the libpython pyDev is linked with, otherwise its standard library and
// packages cannot be loaded.
bool checkEnvironment(const std::string& algorithmFile, const std::string& interpreter, std::string& error) {
	std::string output;
	if (!queryInterpreter(interpreter, "import sys, sysconfig; print(sys.version_info[0], sys.version_info[1], int(bool(sysconfig.get_config_var('Py_GIL_DISABLED'))))", output)) {
		error = algorithmFile + " asks for " + interpreter + " (shebang), which could not be run";
		return false;
	}
	int major = 0, minor = 0, freeThreaded = 0;
	if (sscanf(output.c_str(), "%d %d %d", &major, &minor, &freeThreaded) != 3) {
		error = algorithmFile + " asks for " + interpreter + " (shebang), which did not report its version";
		return false;
	}
	if (major != PY_MAJOR_VERSION || minor != PY_MINOR_VERSION || bool(freeThreaded) != bool(G2S_PYDEV_FREE_THREADED)) {
		error = algorithmFile + " asks for " + interpreter + " (Python " + pythonBuildName(major, minor, freeThreaded) +
		        "), but pyDev was built for Python " + pythonBuildName(PY_MAJOR_VERSION, PY_MINOR_VERSION, G2S_PYDEV_FREE_THREADED) +
		        ". Create the environment from that Python (e.g. python" + std::to_string(PY_MAJOR_VERSION) + "." +
		        std::to_string(PY_MINOR_VERSION) + (G2S_PYDEV_FREE_THREADED ? "t" : "") + " -m venv ...), or rebuild pyDev against the other one.";
		return false;
	}
	return true;
}

std::string directoryOf(const std::string& path) {
	const size_t slash = path.find_last_of('/');
	return slash == std::string::npos ? std::string(".") : path.substr(0, slash);
}

std::string executableDirectory(const char* argv0) {
	if (!argv0) return ".";
	char resolved[PATH_MAX];
	if (realpath(argv0, resolved)) return directoryOf(resolved);
	return directoryOf(argv0);
}

bool fileExists(const std::string& path) { return access(path.c_str(), R_OK) == 0; }

// "-pa" value: "file", "file:Class", "dir/file.py:Class", "/abs/file.py".
// The class defaults to the file name without extension.
bool resolveAlgorithm(const std::string& spec, const std::string& algoDirectory, std::string& filePath, std::string& className, std::string& error) {
	std::string filePart = spec;
	const size_t colon = spec.find_last_of(':');
	const size_t slash = spec.find_last_of('/');
	if (colon != std::string::npos && (slash == std::string::npos || colon > slash)) {
		filePart = spec.substr(0, colon);
		className = spec.substr(colon + 1);
	}
	if (filePart.empty()) { error = "-pa: missing file name"; return false; }
	if (filePart.size() < 3 || filePart.compare(filePart.size() - 3, 3, ".py") != 0) filePart += ".py";
	const size_t stemStart = filePart.find_last_of('/') == std::string::npos ? 0 : filePart.find_last_of('/') + 1;
	if (className.empty()) className = filePart.substr(stemStart, filePart.size() - 3 - stemStart);
	filePath = (filePart[0] == '/') ? filePart : algoDirectory + "/" + filePart;
	if (!fileExists(filePath)) { error = "-pa: Python algorithm not found: " + filePath; return false; }
	return true;
}

void buildOffsets(g2s::DataImage& kernel, g2s::DistanceType searchDistance, std::vector<std::vector<int> >& offsets) {
	std::vector<std::vector<int> > all(1);
	for (size_t dim = 0; dim < kernel._dims.size(); ++dim) {
		const int radius = int(kernel._dims[dim] / 2);
		std::vector<std::vector<int> > next;
		next.reserve(all.size() * size_t(2 * radius + 1));
		for (const std::vector<int>& prefix : all) {
			for (int delta = -radius; delta <= radius; ++delta) {
				next.push_back(prefix);
				next.back().push_back(delta);
			}
		}
		all.swap(next);
	}
	unsigned center = 0;
	for (int dim = int(kernel._dims.size()) - 1; dim >= 0; --dim) center = center * kernel._dims[dim] + kernel._dims[dim] / 2;

	struct Entry { size_t index; float priority; };
	std::vector<Entry> entries;
	entries.reserve(all.size());
	for (size_t i = 0; i < all.size(); ++i) {
		bool zero = true;
		for (int value : all[i]) zero &= (value == 0);
		if (zero) continue; // the node itself is always row 0
		unsigned flat = 0;
		if (!kernel.indexWithDelta(flat, center, all[i])) continue;
		float priority = 0.f;
		bool usable = false;
		for (unsigned v = 0; v < kernel._nbVariable; ++v) {
			const float weight = kernel._data[flat * kernel._nbVariable + v];
			if (std::isfinite(weight) && weight != 0.f) usable = true;
			if (std::isfinite(weight)) priority = std::max(priority, std::fabs(weight));
		}
		if (!usable) continue; // zero/NaN weight: outside the neighbourhood
		if (searchDistance != g2s::KERNEL) {
			float distance2 = 0.f;
			for (int value : all[i]) distance2 += float(value * value);
			priority = -distance2;
		}
		entries.push_back({ i, priority });
	}
	std::stable_sort(entries.begin(), entries.end(), [](const Entry& a, const Entry& b) { return a.priority > b.priority; });
	offsets.clear();
	offsets.reserve(entries.size());
	for (const Entry& entry : entries) offsets.push_back(all[entry.index]);
}

