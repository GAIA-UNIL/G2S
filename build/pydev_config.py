#!/usr/bin/env python3
"""Build configuration for the pyDev algorithm (embedded Python).

Usage: <python> pydev_config.py --check | --cflags | --ldflags | --header FILE

Run it with the Python pyDev should be built against (>= 3.14, with numpy).
If that Python is a virtual environment, pyDev is built against the Python the
venv was created from; the venv itself is not recorded, so deleting it later
does not break pyDev. At run time an algorithm selects its environment with a
shebang line (#!/path/to/env/bin/python); without one, pyDev uses that base
Python.
"""

import glob
import os
import subprocess
import sys
import sysconfig


def fail(message):
    sys.stderr.write("pyDev: " + message + "\n")
    sys.exit(1)


def base_python():
    if sys.prefix != sys.base_prefix:  # running inside a venv
        return os.path.realpath(getattr(sys, "_base_executable", sys.executable))
    return os.path.realpath(sys.executable)


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    if sys.version_info < (3, 14):
        fail(f"Python >= 3.14 is required, {sys.executable} is {sys.version.split()[0]} "
             "(run: make pydev PYDEV_PYTHON=/path/to/python3.14t)")
    try:
        import numpy
    except ImportError:
        fail(f"numpy is not installed for {sys.executable} (needed to build pyDev)")

    config = sysconfig.get_config_var
    if mode == "--check":
        build = "free-threaded" if config("Py_GIL_DISABLED") else "with GIL"
        base = base_python()
        print(f"pyDev: building against {base} (Python {sys.version.split()[0]}, {build}, numpy {numpy.__version__})")
        if subprocess.run([base, "-I", "-c", "import numpy"], capture_output=True).returncode != 0:
            print(f"pyDev: note: numpy is not installed for {base}; algorithms without a shebang line will fail. "
                  "Install numpy there, or start algorithms with #!/path/to/env/bin/python")
    elif mode == "--cflags":
        print(f"-I{sysconfig.get_path('include')} -I{numpy.get_include()}")
    elif mode == "--ldflags":
        ldversion = config("LDVERSION")
        library_dir = None
        for candidate in (config("LIBDIR"), config("LIBPL")):
            if candidate and glob.glob(os.path.join(candidate, f"libpython{ldversion}.*")):
                library_dir = candidate
                break
        if library_dir is None:
            fail(f"libpython{ldversion} not found (Python must provide a shared or static libpython)")
        flags = [f"-L{library_dir}", f"-lpython{ldversion}"]
        flags += (config("LIBS") or "").split() + (config("SYSLIBS") or "").split()
        if config("Py_ENABLE_SHARED"):
            flags.append(f"-Wl,-rpath,{library_dir}")
        print(" ".join(flags))
    elif mode == "--header":
        if len(sys.argv) < 3:
            fail("--header needs an output file")
        escaped = base_python().replace("\\", "\\\\").replace('"', '\\"')
        with open(sys.argv[2], "w") as handle:
            handle.write("// Generated by build/pydev_config.py: the Python pyDev is built against.\n"
                         f'#define G2S_PYDEV_BASE_PYTHON "{escaped}"\n')
    else:
        fail("unknown option " + mode)


if __name__ == "__main__":
    main()
